  function isExcluded(node) {
    if (!node) return true;
    var el = node.nodeType === 1 ? node : node.parentElement;
    if (!el) return false;
    if (EXCLUDED_TAGS[el.tagName]) return true;

    // Never exclude autocomplete menus, popups, options, or tool cards!
    if (el.closest('[data-testid*="menu-option"], [data-testid*="slash-command"], [data-testid*="mention"], .cm-tooltip, .cm-tooltip-autocomplete, [role="listbox"], [role="option"], [role="menuitem"], .tabular-nums, [data-testid*="thought"], [data-testid*="step"], [data-testid*="tool"], button, [role="button"], .tool-card')) {
      return false;
    }

    // Exclude actual code blocks and editor input lines (do NOT exclude entire .cm-editor)
    if (el.closest('pre, code, .cm-content, .cm-line, .monaco-editor, .syntax-highlighter, [data-language], [data-no-translate], .notranslate')) {
      return true;
    }

    var messageBody = el.closest('.prose, .markdown-content, [data-testid="message-content"]');
    if (messageBody) {
      return true;
    }
    return false;
  }

