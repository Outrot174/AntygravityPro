  function translateElementAttributes(el) {
    if (!el || el.nodeType !== 1) return;
    var attrs = ['placeholder', 'title', 'aria-label', 'data-tooltip-content'];
    for (var i = 0; i < attrs.length; i++) {
      var a = attrs[i];
      if (el.hasAttribute(a)) {
        var v = el.getAttribute(a);
        var tr = translateText(v);
        if (tr !== v) el.setAttribute(a, tr);
      }
    }
    if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
      var val = el.value;
      var trVal = translateText(val);
      if (trVal !== val) el.value = trVal;
    }
  }

  function translateDomNode(node) {
    if (!node) return;
    if (node.nodeType === 3) {
      if (!isExcluded(node)) {
        var val = node.nodeValue;
        if (val && /[a-zA-Z]/.test(val)) {
          var tr = translateText(val);
          if (tr !== val) {
            node.nodeValue = tr;
          }
        }
      }
    } else if (node.nodeType === 1) {
      if (isExcluded(node)) return;
      translateElementAttributes(node);
      for (var c = node.firstChild; c; c = c.nextSibling) {
        translateDomNode(c);
      }
    }
  }

  var pendingQueue = [];
  var isScheduled = false;

  function flushBatch() {
    isScheduled = false;
    var queue = pendingQueue.splice(0, pendingQueue.length);
    for (var i = 0; i < queue.length; i++) {
      translateDomNode(queue[i]);
    }
  }

  function queueNode(node) {
    pendingQueue.push(node);
    if (!isScheduled) {
      isScheduled = true;
      if (window.requestAnimationFrame) {
        window.requestAnimationFrame(flushBatch);
      } else {
        setTimeout(flushBatch, 16);
      }
    }
  }

